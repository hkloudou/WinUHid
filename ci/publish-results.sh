#!/usr/bin/env bash
# Publishes the latest run's reports and log tails to the single `ci-results` branch,
# so a run's outcome can be read with plain git. The branch always holds one commit.
#
# Expects the per-job `logs-*` artifacts unpacked under ./results/<artifact name>/.
set -u

work="$RUNNER_TEMP/ci-results"
rm -rf "$work" && mkdir -p "$work"

{
  echo "# Latest dev build results"
  echo
  echo "Generated by the \`Dev build\` workflow. This branch is overwritten on every run; do not edit it."
  echo
  echo "- Commit: $GITHUB_SHA"
  echo "- Run: $GITHUB_SERVER_URL/$GITHUB_REPOSITORY/actions/runs/$GITHUB_RUN_ID (attempt $GITHUB_RUN_ATTEMPT)"
  echo "- Finished (UTC): $(date -u +%Y-%m-%dT%H:%M:%S)"
  echo "- Build: ${RESULT_BUILD:-?}"
  echo "- Install tests: ${RESULT_INSTALL:-?}"
  echo
} > "$work/README.md"

shopt -s nullglob
for dir in results/logs-*/; do
  job="$(basename "$dir")"; job="${job#logs-}"
  {
    echo "---"
    echo
    echo "# Job: $job"
    echo
    if [ -f "$dir/report.md" ]; then cat "$dir/report.md"; else echo "(no report was written)"; fi
    echo
  } >> "$work/README.md"
  # Tails only: enough to diagnose a failure, small enough to read.
  if [ -d "$dir/logs" ]; then
    mkdir -p "$work/logs/$job"
    for f in "$dir"/logs/*; do
      [ -f "$f" ] && tail -n 400 "$f" > "$work/logs/$job/$(basename "$f")"
    done
  fi
done

cd "$work" || exit 0
git init -q -b ci-results
git add -A
git -c user.name='github-actions[bot]' -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
  commit -q -m "Results for $GITHUB_SHA (run $GITHUB_RUN_ID)"
if git push --force --quiet "https://x-access-token:${GITHUB_TOKEN}@github.com/${GITHUB_REPOSITORY}.git" HEAD:refs/heads/ci-results; then
  echo "Results pushed to ci-results"
else
  echo "::warning::Could not push results to the ci-results branch."
fi
exit 0
